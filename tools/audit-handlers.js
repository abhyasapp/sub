#!/usr/bin/env node
/**
 * tools/audit-handlers.js
 *
 * Scans index.html / user.html / admin.html for data-on-* handlers,
 * extracts the top-level global each one calls, verifies that global
 * is declared somewhere under js/, and (with --write-expose) writes
 * js/core/expose.js so actions.js can find it on window.
 *
 * Usage:
 *   node tools/audit-handlers.js                 (audit only, exit 1 if missing)
 *   node tools/audit-handlers.js --write-expose  (audit + write expose.js)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const HTML_FILES = ['index.html', 'user.html', 'admin.html'];
const EXPOSE_PATH = path.join(ROOT, 'js', 'core', 'expose.js');

// Never treat these as app-level globals even if they appear in a handler.
const SKIP = new Set([
  'event', 'this', 'true', 'false', 'null', 'undefined',
  'window', 'document', 'location', 'navigator', 'history',
  'Object', 'Array', 'String', 'Number', 'Boolean', 'JSON',
  'Math', 'Date', 'RegExp', 'Promise', 'Error', 'Symbol',
  'setTimeout', 'setInterval', 'clearTimeout', 'clearInterval',
  'parseInt', 'parseFloat', 'isNaN', 'isFinite',
  'alert', 'confirm', 'prompt', 'encodeURIComponent', 'decodeURIComponent',
  'scrollTo', 'scrollIntoView', 'focus', 'blur',
]);

// ─── 1. Collect handler identifiers from HTML ─────────────────────
const attrs = ['data-on-click', 'data-on-change', 'data-on-input',
               'data-on-submit', 'data-on-error', 'data-on-load',
               'data-on-toggle', 'data-on-keydown'];
const used = new Set();
const usedIn = new Map(); // name -> [file:line]

for (const file of HTML_FILES) {
  const p = path.join(ROOT, file);
  if (!fs.existsSync(p)) continue;
  const lines = fs.readFileSync(p, 'utf8').split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    for (const attr of attrs) {
      const re = new RegExp(attr + '="([^"]*)"', 'g');
      let m;
      while ((m = re.exec(lines[i]))) {
        // Blank out string literals first: the "index" in
        // ACT.go('index.html?pay=1') is an argument, not a handler.
        const expr = m[1].replace(/'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"/g, (s) => ' '.repeat(s.length));
        // Match the first identifier before a '.' or '(' — not preceded by '.', word char, or '$'.
        const idRe = /(?<![.\w$])([A-Za-z_$][\w$]*)\s*(?:\.|\()/g;
        let im;
        while ((im = idRe.exec(expr))) {
          const name = im[1];
          if (SKIP.has(name)) continue;
          used.add(name);
          if (!usedIn.has(name)) usedIn.set(name, []);
          usedIn.get(name).push(`${file}:${i + 1}`);
        }
      }
    }
  }
}

// ─── 2. Collect top-level declarations from JS ────────────────────
const defined = new Map(); // name -> [file, ...]
const jsFiles = [];
(function walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.js')) jsFiles.push(p);
  }
})(path.join(ROOT, 'js'));

for (const f of jsFiles) {
  const src = fs.readFileSync(f, 'utf8');
  const rel = path.relative(ROOT, f).replace(/\\/g, '/');
  // Top-level declaration heuristic: 0–4 spaces indent, then const/let/var/function/class
  const declRe = /^[ \t]{0,4}(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = declRe.exec(src))) {
    const name = m[1];
    if (!defined.has(name)) defined.set(name, []);
    defined.get(name).push(rel);
  }
  // Explicit window.X = anywhere
  const winRe = /\bwindow\.([A-Za-z_$][\w$]*)\s*=/g;
  while ((m = winRe.exec(src))) {
    const name = m[1];
    if (!defined.has(name)) defined.set(name, []);
    defined.get(name).push(rel);
  }
}

// ─── 3. Diff ──────────────────────────────────────────────────────
const resolved = [];
const missing = [];
for (const name of used) {
  if (defined.has(name)) resolved.push(name);
  else missing.push(name);
}
resolved.sort();
missing.sort();

console.log(`Handlers used in HTML: ${used.size}`);
console.log(`Resolved in js/:       ${resolved.length}`);
console.log(`Missing:               ${missing.length}`);

if (missing.length) {
  console.log('\nMissing (each needs `window.X = X;` at the bottom of the file that defines X, or a load-order fix):');
  for (const name of missing) {
    const where = (usedIn.get(name) || []).slice(0, 2).join(', ');
    console.log(`  ✗ ${name}    used at ${where}`);
  }
}

// ─── 4. Write js/core/expose.js ───────────────────────────────────
const doWrite = process.argv.includes('--write-expose');

if (doWrite) {
  const lines = [
    '/* =====================================================================',
    ' * js/core/expose.js  — AUTO-GENERATED, do not edit by hand.',
    ' * Generated by: node tools/audit-handlers.js --write-expose',
    ' * Purpose:      copy every top-level global onto `window` so',
    ' *               js/core/actions.js can look up handler names safely',
    ' *               (data-on-click="X.method(...)" needs window.X).',
    ' * ===================================================================== */',
    '(function () {',
  ];
  for (const name of resolved) {
    lines.push(`  try { if (typeof ${name} !== 'undefined') window.${name} = ${name}; } catch (e) { /* not yet defined at this point */ }`);
  }
  lines.push('})();');
  lines.push('');
  fs.mkdirSync(path.dirname(EXPOSE_PATH), { recursive: true });
  fs.writeFileSync(EXPOSE_PATH, lines.join('\n'), 'utf8');
  console.log(`\n✓ Wrote js/core/expose.js (${resolved.length} names)`);
}

process.exit(missing.length ? 1 : 0);