#!/usr/bin/env node
// tools/build-content-index.mjs — count the questions in every content file and write js/data/content-index.js
//
//   node tools/build-content-index.mjs <path-to-content-repo>/content  [--out js/data/content-index.js] [--check]
//
// Why: the app learns each set's size lazily (only after it is opened), so on a fresh install it cannot know how big
// the Level 7 + GK syllabus is. A committed index makes the 60-day sprint plan exact from the very first launch.
// Counting follows the app's own parser (js/core/question.js normQ): a question needs text and at least 2 options.
// Encrypted envelopes cannot be counted here unless they carry a numeric "count"; they are listed and left to the app.
import fs from 'node:fs';
import path from 'node:path';

export function countQuestions(raw) {
  if (raw && typeof raw === 'object' && !Array.isArray(raw) && raw.success === false) return 0;
  let a = Array.isArray(raw) ? raw : (raw && (raw.questions || raw.data || raw.quiz || raw.items || raw.result)) || null;
  if (!Array.isArray(a) && a === null && raw && typeof raw === 'object') {
    const vals = Object.values(raw);
    if (vals.length && vals[0] && (vals[0].q || vals[0].question || vals[0].Question)) a = vals;
  }
  if (!Array.isArray(a)) return null;
  let n = 0;
  for (const q of a) {
    if (!q || typeof q !== 'object') continue;
    const text = q.q || q.question || q.Question || q.stem || q.ques || q.text || '';
    if (!text) continue;
    let options = q.options || q.opts || q.choices || q.Options;
    if (!Array.isArray(options)) {
      options = [q.a || q.A, q.b || q.B, q.c || q.C, q.d || q.D, q.e || q.E].filter((x) => x !== undefined && x !== null && x !== '');
    }
    if (Array.isArray(options) && options.length >= 2) n++;
  }
  return n;
}

export function buildIndex(root) {
  const index = {}, skipped = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== '.git' && e.name !== 'node_modules') walk(p); continue; }
      if (!e.name.endsWith('.json')) continue;
      const fid = path.relative(root, p).replace(/\\/g, '/').replace(/\.json$/, '');
      let data;
      try { data = JSON.parse(fs.readFileSync(p, 'utf8')); } catch { skipped.push(fid + ' (not valid JSON)'); continue; }
      if (data && data.enc === 1) {
        const c = Number(data.count ?? data.n ?? data.total);
        if (Number.isFinite(c) && c >= 0) index[fid] = c; else skipped.push(fid + ' (encrypted, no count)');
        continue;
      }
      const n = countQuestions(data);
      if (n === null) skipped.push(fid + ' (unrecognised format)'); else index[fid] = n;
    }
  })(root);
  return { index, skipped };
}

export function render(index) {
  const keys = Object.keys(index).sort();
  const body = keys.map((k) => '  ' + JSON.stringify(k) + ': ' + index[k]).join(',\n');
  return '// AUTO-GENERATED by tools/build-content-index.mjs - do not edit by hand.\n' +
         '// File id -> number of questions. Lets the sprint plan the whole syllabus from the first launch.\n' +
         'window.CONTENT_INDEX = Object.assign(window.CONTENT_INDEX || {}, {\n' + body + '\n});\n';
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const args = process.argv.slice(2);
  const root = args.find((a) => !a.startsWith('--'));
  const out = args.includes('--out') ? args[args.indexOf('--out') + 1] : path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'js/data/content-index.js');
  if (!root || !fs.existsSync(root)) { console.error('Usage: node tools/build-content-index.mjs <content-folder> [--out file] [--check]'); process.exit(2); }
  const { index, skipped } = buildIndex(root);
  const total = Object.values(index).reduce((a, b) => a + b, 0);
  const text = render(index);
  console.log(`${Object.keys(index).length} files, ${total} questions` + (skipped.length ? `, ${skipped.length} not counted:` : ''));
  skipped.slice(0, 20).forEach((s) => console.log('  - ' + s));
  if (args.includes('--check')) { process.exit(fs.existsSync(out) && fs.readFileSync(out, 'utf8') === text ? 0 : 1); }
  fs.writeFileSync(out, text);
  console.log('wrote ' + out);
}
